"""Pilot: does reading the user's unresolved need (from linguistic and emotional cues) make an LLM solve it?

Cases: DialMAGE test dialogues, at a user turn labeled dissatisfied/abusive that repeats an earlier
request of the same user (the need was not met). Three reply conditions, generated by Claude:
  A baseline   - reply to the last message
  B direct     - reply concretely and helpfully (no diagnosis step)
  C diagnose   - first read the dialogue for what is still unresolved and how the user feels, then solve it
A different model family (Codex) judges blind, with the three replies shuffled per case.

Usage: python3 intervene.py data/ runs/pilot N
"""
import json
import os
import random
import subprocess
import sys
from pathlib import Path

from analyze import NEG, final_label, jaccard
from repair import brief, log_for

BATCH = 10
SEED = 0
DOMAIN = ("You are a travel-information assistant for Cambridge, UK: restaurants, hotels and guesthouses, "
          "attractions, trains, taxis, the hospital and police. You have no live database; use what you know, "
          "and when booking, say what you booked and give a reference like ABC123.")
PROMPTS = {
    "A_baseline": DOMAIN + " Write the assistant's next reply to the last user message.",
    "B_direct": DOMAIN + (" Write the assistant's next reply to the last user message. Be concrete and helpful: "
                          "give the user a specific answer, not a question back, unless one detail is truly missing."),
    "C_diagnose": DOMAIN + (" Before writing, read the whole dialogue the way a linguist would. Find what the user asked "
                            "for that has still not been delivered. Signs: the user repeats or rephrases an earlier "
                            "request, says no / not / already / again, drops politeness, or writes shorter turns. Name "
                            "how the user feels now. Then write the assistant's next reply: deliver the unresolved thing "
                            "first, concretely. If it cannot be done, say exactly why in one sentence and give the "
                            "closest option. Do not repeat earlier assistant text. Apologize only if it adds something."),
}
REPAIR_TAIL = (" Below each dialogue is a reading of the user prepared for you: the escalation stage and its cues, "
               "what is still pending, real database rows, what you already said, and a response policy. Use the "
               "database rows instead of your own knowledge, follow the policy, and write the assistant's next reply.")
LEDGER_TAIL = (" Below each dialogue is what the user has requested and real database rows for it. Use the database "
               "rows instead of your own knowledge, and write the assistant's next reply.")
PROMPTS["D_repair"] = DOMAIN + REPAIR_TAIL
PROMPTS["E_ledger_db"] = DOMAIN + LEDGER_TAIL
CONDITIONS = os.environ.get("CONDITIONS", ",".join(PROMPTS)).split(",")
OUT_A = 'Return only JSON: {"<case id>": "<reply>", ...} for every case.'
OUT_C = 'Return only JSON: {"<case id>": {"unresolved": "...", "feeling": "...", "reply": "..."}, ...} for every case.'
JUDGE = """You are judging replies from a travel assistant (Cambridge, UK) in conversations where the user is
dissatisfied and has had to repeat a request. For each case you get the dialogue and candidate replies {letters}.
Judge whether the reply would get the user what they need. Do not reward length.
For each case:
- need: one sentence, what the user still needs at this point.
- For each candidate: resolves = 2 (delivers the need), 1 (partly, or moves clearly toward it), 0 (does not);
  give_up = true if a user in this state would likely give up after this reply;
  repeats = true if the reply repeats a question or information the assistant already gave, instead of understanding the user.
- best: the one candidate letter that best gets the user what they need.
Return only JSON: {{"<case id>": {{"need": "...", "{first}": {{"resolves": 0, "give_up": false, "repeats": false}}, ..., "best": "{first}"}}, ...}}"""
LETTERS = "VWXYZ"


def render(log, upto):
    lines = []
    for i in range(upto + 1):
        text = log[i]["text"].strip()
        if text:
            lines.append(("User: " if i % 2 == 0 else "Assistant: ") + text)
    return "\n".join(lines)


def select_cases(root, n):
    split = json.load(open(root / "data-split.json"))
    part = split[os.environ.get("SPLIT", "test")]
    test_ids = set(part["dialmage"]) if isinstance(part, dict) else set(part)
    data = json.load(open(root / "emowoz-dialmage.json"))
    cases = []
    for did, dialogue in data.items():
        if did not in test_ids:
            continue
        log = dialogue["log"]
        earlier = []
        for i in range(0, len(log), 2):
            text = log[i]["text"]
            if final_label(log[i]) in NEG and any(jaccard(text, e) >= 0.5 for e in earlier):
                cases.append({"id": f"{did}#{i}", "dialogue": render(log, i)})
                break
            earlier.append(text)
    random.Random(SEED).shuffle(cases)
    return cases[:n]


def parse_json(text):
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end < 0:
        raise ValueError(f"no JSON in model output: {text[:300]!r}")
    return json.loads(text[start:end + 1])


def claude(prompt, model="sonnet"):
    for attempt in range(3):
        out = subprocess.run(["claude", "-p", "--model", model, prompt], capture_output=True, text=True, timeout=1800, check=True)
        try:
            return parse_json(out.stdout)
        except ValueError:
            if attempt == 2:
                raise


JUDGER = os.environ.get("JUDGER", "codex")
JUDGE_REF = os.environ.get("JUDGE_REF") == "1"
REF_NOTE = ("\nReference database rows for the user's current request, to check facts. A train, venue, time or "
            "booking that contradicts them, or is not in them, is wrong and must not get resolves = 2.\n")


def codex(prompt, last_path):
    subprocess.run(["codex", "exec", "--skip-git-repo-check", "-c", 'model_reasoning_effort="high"',
                    "--output-last-message", str(last_path), prompt],
                   capture_output=True, text=True, timeout=1800, check=True)
    return parse_json(Path(last_path).read_text())


GEN = os.environ.get("GEN", "claude:sonnet")


def ollama_call(model, text):
    return subprocess.run(["ollama", "run", model], input=text, capture_output=True, text=True,
                          timeout=600, check=True).stdout.strip()


def ollama_one(prompt, case, cond):
    """Small models do not follow a combined notes+reply format, so C runs as two calls: read, then reply."""
    model = GEN.split(":", 1)[1]
    if cond != "C_diagnose":
        case = with_reading(case, cond)
        return {"reply": ollama_call(model, f"{prompt}\nWrite only the assistant's reply.\n\n{case['dialogue']}\nAssistant:")}
    notes = ollama_call(model, (
        "Read this dialogue the way a linguist would. Answer in two short lines: "
        "1) What has the user asked for that has still not been delivered? Look for repeated or rephrased requests, "
        "no / not / already / again, dropped politeness, shorter turns. 2) How does the user feel now?\n\n"
        + case["dialogue"]))
    reply = ollama_call(model, (
        f"{prompt}\n\nYour reading of the user:\n{notes}\n\nWrite only the assistant's reply.\n\n"
        f"{case['dialogue']}\nAssistant:"))
    return {"notes": notes, "reply": reply}


_DATA = {}


def reading(case, cond):
    if "dm" not in _DATA:
        _DATA["dm"] = json.load(open(Path(__file__).resolve().parent / "data" / "emowoz-dialmage.json"))
    log, i = log_for(case["id"], _DATA["dm"])
    text = brief(log, i)[0]
    if cond == "E_ledger_db":
        text = "\n".join(line for line in text.splitlines()
                         if line.startswith(("Pending request", "  ", "No domain")))
    return f"\n[Reading of the user]\n{text}"


def with_reading(case, cond):
    if cond in ("D_repair", "E_ledger_db"):
        return dict(case, dialogue=case["dialogue"] + "\n" + reading(case, cond))
    return case


def batches(items):
    for i in range(0, len(items), BATCH):
        yield items[i:i + BATCH]


def cases_block(batch):
    return "\n\n".join(f"### Case {c['id']}\n{c['dialogue']}" for c in batch)


def generate(cases, run_dir):
    path = run_dir / "replies.json"
    replies = json.loads(path.read_text()) if path.exists() else {}
    for cond in CONDITIONS:
        prompt = PROMPTS[cond]
        replies.setdefault(cond, {})
        if GEN.startswith("ollama:"):
            for c in [c for c in cases if c["id"] not in replies[cond]]:
                replies[cond][c["id"]] = ollama_one(prompt, c, cond)
                path.write_text(json.dumps(replies, indent=1))
            continue
        fmt = OUT_C if cond == "C_diagnose" else OUT_A
        for _attempt in range(3):
            todo = [c for c in cases if c["id"] not in replies[cond]]
            for batch in batches(todo):
                got = claude(f"{prompt}\n\n{fmt}\n\n{cases_block([with_reading(c, cond) for c in batch])}")
                for c in batch:
                    if c["id"] in got:
                        r = got[c["id"]]
                        replies[cond][c["id"]] = r if isinstance(r, dict) else {"reply": r}
                path.write_text(json.dumps(replies, indent=1))
        missing = [c["id"] for c in cases if c["id"] not in replies[cond]]
        if missing:
            raise ValueError(f"{cond}: model skipped cases {missing} after 3 attempts")
    return replies


def judge(cases, replies, run_dir):
    tag = ("" if JUDGER == "codex" else "_" + JUDGER.replace(":", "-")) + ("_ref" if JUDGE_REF else "")
    path = run_dir / f"judgments{tag}.json"
    done = json.loads(path.read_text()) if path.exists() else {}
    rng = random.Random(SEED + 1)
    order_path = run_dir / "order.json"
    order = json.loads(order_path.read_text()) if order_path.exists() else {}
    for c in cases:
        if c["id"] not in order:
            conds = list(CONDITIONS)
            rng.shuffle(conds)
            order[c["id"]] = dict(zip(LETTERS[-len(conds):], conds))
    order_path.write_text(json.dumps(order, indent=1))
    todo = [c for c in cases if c["id"] not in done]
    for k, batch in enumerate(batches(todo)):
        block = []
        for c in batch:
            opts = "\n".join(f"{slot}: {replies[cond][c['id']]['reply']}" for slot, cond in order[c["id"]].items())
            ref = ""
            if JUDGE_REF:
                rows = [line for line in reading(c, "E_ledger_db").splitlines() if line.startswith(("Pending request", "  "))]
                ref = REF_NOTE + ("\n".join(rows) if rows else "(no database rows for this request)") + "\n"
            block.append(f"### Case {c['id']}\n{c['dialogue']}\n{ref}\nCandidate replies:\n{opts}")
        letters = LETTERS[-len(CONDITIONS):]
        prompt = JUDGE.format(letters=", ".join(letters), first=letters[0]) + "\n\n" + "\n\n".join(block)
        if JUDGER == "codex":
            got = codex(prompt, run_dir / f"judge_last_{len(done)}_{k}.txt")
        else:
            got = claude(prompt, model=JUDGER.split(":", 1)[1])
        done.update({c["id"]: got[c["id"]] for c in batch if c["id"] in got})
        path.write_text(json.dumps(done, indent=1))
    missing = [c["id"] for c in cases if c["id"] not in done]
    if missing:
        raise ValueError(f"judge skipped cases {missing}; rerun to retry them")
    return order, done


def summarize(cases, order, judgments):
    rows = []
    for c in cases:
        j = judgments[c["id"]]
        by_cond = {cond: j[slot] for slot, cond in order[c["id"]].items()}
        best = order[c["id"]][j["best"]]
        rows.append({cond: {"resolves": v["resolves"], "give_up": bool(v["give_up"]), "repeats": bool(v["repeats"]), "best": cond == best}
                     for cond, v in by_cond.items()})

    def mean(sample, cond, key):
        return sum(float(r[cond][key]) for r in sample) / len(sample)

    def ci(cond, key, diff_from=None, n=4000):
        rng = random.Random(SEED + 2)
        vals = []
        for _ in range(n):
            s = [rows[rng.randrange(len(rows))] for _ in rows]
            v = mean(s, cond, key) - (mean(s, diff_from, key) if diff_from else 0)
            vals.append(v)
        vals.sort()
        return [round(vals[int(0.025 * n)], 3), round(vals[int(0.975 * n) - 1], 3)]

    out = {"n": len(rows)}
    for cond in CONDITIONS:
        out[cond] = {key: {"mean": round(mean(rows, cond, key), 3), "ci95": ci(cond, key)}
                     for key in ("resolves", "give_up", "repeats", "best")}
    pairs = [(a, b) for a in CONDITIONS for b in CONDITIONS if CONDITIONS.index(a) > CONDITIONS.index(b)]
    for a, b in pairs:
        out[f"{a} - {b}"] = {key: {"diff": round(mean(rows, a, key) - mean(rows, b, key), 3), "ci95": ci(a, key, b)}
                             for key in ("resolves", "give_up", "repeats")}
    return out


def main():
    root, run_dir, n = Path(sys.argv[1]), Path(sys.argv[2]), int(sys.argv[3])
    run_dir.mkdir(parents=True, exist_ok=True)
    cases = select_cases(root, n)
    (run_dir / "cases.json").write_text(json.dumps(cases, indent=1))
    replies = generate(cases, run_dir)
    order, judgments = judge(cases, replies, run_dir)
    summary = summarize(cases, order, judgments)
    tag = ("" if JUDGER == "codex" else "_" + JUDGER.replace(":", "-")) + ("_ref" if JUDGE_REF else "")
    (run_dir / f"summary{tag}.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
